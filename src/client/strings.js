const DIGITS = "۰۱۲۳۴۵۶۷۸۹";
const grouped = new Intl.NumberFormat("fa-IR", { maximumFractionDigits: 0 });

/** Persian digits without grouping, for small counters such as wave numbers. */
export function fa(value) {
  return String(value).replace(/\d/g, (d) => DIGITS[d]);
}

/** Persian digits with Persian thousands separators. */
export function formatNumber(value) {
  return grouped.format(Math.round(value));
}

/** @param {number} seconds */
export function formatTime(seconds) {
  const s = Math.max(0, Math.floor(seconds));
  return fa(`${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`);
}

